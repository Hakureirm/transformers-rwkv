"""Aggregate logs/gpu/measure-*.json into SUMMARY.md tables. Reads raw logs only; never edits them."""

import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
G = os.path.join(HERE, "logs", "gpu")
REPOS = ["RWKV7-G1k-1.5B-20260930", "RWKV7-G1k-2.9B-20260930", "RWKV7-G1k-7.2B-20260930",
         "RWKV7-G1k-13.3B-20260930", "RWKV7-G1j-1.5B-20260831", "RWKV7-1.5B-20260805"]


def runs():
    out = []
    for f in sorted(glob.glob(os.path.join(G, "measure-*.json"))):
        r = json.load(open(f))
        r["_file"] = os.path.relpath(f, HERE)
        r["_invalid"] = r["arm"].startswith("RW") and not (r.get("model_class") or "").startswith("transformers.")
        out.append(r)
    return out


def latest(rs, repo, arm, dtype, variant=""):
    c = [r for r in rs if r["repo"] == repo and r["arm"] == arm and r["dtype"] == dtype
         and (r.get("variant") or "") == variant and not r["_invalid"]]
    return c[-1] if c else None


def comp_stats(r, comp):
    cs = {p: rec["comparisons"][comp] for p, rec in r["prompts"].items() if comp in rec["comparisons"]}
    if not cs:
        return None
    div = {p: c for p, c in cs.items() if not c["free_identical"]}
    unex = {p: c for p, c in div.items() if not c["divergence"]["explained_by_precision"]}
    ties = [p for p, c in unex.items()
            if abs(c["divergence"]["anchor_margin"] - abs(c["divergence"]["delta_top1"])
                   - abs(c["divergence"]["delta_top2"])) < 1e-3]
    return {"n": len(cs), "identical": len(cs) - len(div), "diverged": len(div), "unexplained": sorted(unex),
            "unexplained_ties": sorted(ties),
            "pre_abs": max(c["prefill_max_abs"] for c in cs.values()),
            "pre_rel": max(c["prefill_max_rel"] for c in cs.values()),
            "fd_abs": max(c["forced_max_abs"] for c in cs.values()),
            "fd_rel": max(c["forced_max_rel"] for c in cs.values()),
            "first_div": sorted(c["first_divergence"] for c in div.values()),
            "margins": sorted(round(c["divergence"]["anchor_margin"], 4) for c in div.values())}


def main():
    rs = runs()
    L = ["# GPU summary (generated by summarize.py from logs/gpu/measure-*.json)", ""]
    L.append("## Runs")
    L.append("| repo | arm | dtype | variant | GPU | code sha | wkv | load s | total s | log |")
    L.append("|---|---|---|---|---|---|---|---|---|---|")
    for r in rs:
        L.append(f"| {r['repo']} | {r['arm']}{' (INVALID: ' + r['model_class'] + ')' if r['_invalid'] else ''} | "
                 f"{r['dtype']} | {r.get('variant') or ''} | {r['env'].get('gpu')} | {r.get('code_sha', '')[:10]} | "
                 f"{(r.get('wkv_impl') or '-').split('.')[-1]} | {r['load_secs']} | {round(r['finished'] - r['started'])} | "
                 f"`{r['_file']}` |")
    L.append("")
    for comp, title in (("vs_OFF_fp32", "vs OFF fp32 (anchor)"), ("vs_OFF_same", "vs OFF same dtype"),
                        ("vs_RWtorch_same", "vs RW-torch same dtype")):
        L.append(f"## {title}")
        L.append("| repo | arm | dtype | variant | identical/26 | prefill max abs | prefill max rel | forced max abs | "
                 "forced max rel | unexplained (criterion) | of which exact ties |")
        L.append("|---|---|---|---|---|---|---|---|---|---|---|")
        for repo in REPOS:
            for arm in ("PR", "RW-torch", "RW-fla", "OFF"):
                for dtype in ("float32", "bfloat16"):
                    for variant in ("", "safe_gate64"):
                        r = latest(rs, repo, arm, dtype, variant)
                        if r is None:
                            continue
                        s = comp_stats(r, comp)
                        if s is None:
                            continue
                        L.append(f"| {repo} | {arm} | {dtype} | {variant} | {s['identical']}/{s['n']} | "
                                 f"{s['pre_abs']:.2e} | {s['pre_rel']:.2e} | {s['fd_abs']:.2e} | {s['fd_rel']:.2e} | "
                                 f"{', '.join(s['unexplained']) or '-'} | {', '.join(s['unexplained_ties']) or '-'} |")
        L.append("")
    L.append("## Q2: RW vs PR free continuations (G1k-1.5B)")
    for dtype in ("float32", "bfloat16"):
        pr = latest(rs, "RWKV7-G1k-1.5B-20260930", "PR", dtype)
        for arm in ("RW-torch", "RW-fla"):
            rw = latest(rs, "RWKV7-G1k-1.5B-20260930", arm, dtype)
            if pr and rw:
                same = [p for p in pr["prompts"] if pr["prompts"][p]["free_tokens"] == rw["prompts"][p]["free_tokens"]]
                diff = {p: next(i for i, (a, b) in enumerate(zip(pr["prompts"][p]["free_tokens"],
                                                                  rw["prompts"][p]["free_tokens"])) if a != b)
                        for p in pr["prompts"] if p not in same}
                L.append(f"- {dtype}: PR vs {arm}: identical {len(same)}/{len(pr['prompts'])}; "
                         f"first differing step per prompt: {diff or '-'}")
    L.append("")
    L.append("## Batch (4, left padding) and packed checks")
    for r in rs:
        if r["_invalid"]:
            continue
        b = r.get("batch_left_padding")
        if b:
            key = "last_prefill_logit_max_abs" if "last_prefill_logit_max_abs" in b[0] else "last_logit_max_abs"
            L.append(f"- {r['repo']} {r['arm']} {r['dtype']} (`{r['_file']}`): tokens identical "
                     f"{sum(x['tokens_identical'] for x in b)}/{len(b)}, max last-prefill |d| "
                     f"{max(x[key] for x in b):.2e}" + "".join(
                         f"; divergence {x['id']}: {x['divergence']}" for x in b if "divergence" in x))
        if r.get("packed"):
            L.append(f"- packed {r['repo']} {r['arm']} {r['dtype']}: {json.dumps(r['packed'])}")
    L.append("")
    L.append("## generate() vs manual cached loop (RW arms, first 4 lambada prompts)")
    for r in rs:
        if r["_invalid"] or not r["arm"].startswith("RW"):
            continue
        g = [rec.get("generate_equals_manual") for rec in r["prompts"].values() if "generate_equals_manual" in rec]
        if g:
            L.append(f"- {r['repo']} {r['arm']} {r['dtype']} {r.get('variant') or ''}: {sum(g)}/{len(g)}")
    L.append("")
    L.append("## Official runtime bf16 vs fp32 (offline anchor comparison, no forced leg)")
    for f in sorted(glob.glob(os.path.join(G, "anchors-*.json"))):
        a = json.load(open(f))
        ps = a["prompts"].values()
        L.append(f"- {a['repo']} {a['a']} vs {a['b']}: identical {sum(x['free_identical'] for x in ps)}/{len(a['prompts'])}, "
                 f"prefill max abs {max(x['prefill_max_abs'] for x in ps):.2e}, max rel {max(x['prefill_max_rel'] for x in ps):.2e} "
                 f"(`{os.path.relpath(f, HERE)}`)")
    open(os.path.join(G, "SUMMARY.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
